"""Tests for scripts/requirements_review.py. No network: the PyPI version
endpoint answers from a fake fetch, and the directories are written to
pytest's tmp_path."""

import json
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parent
REPO = SCRIPTS.parent
sys.path.insert(0, str(SCRIPTS))
import requirements_review as R  # noqa: E402

HASH = "--hash=sha256:" + "a" * 64
CONFIG = REPO / "serve_api" / "lockfile-review.json"


def req(pins, extra=()):
    lines = ["#", "# autogenerated by pip-compile", "#"]
    lines += list(extra)
    for name, version in sorted(pins.items()):
        lines += [f"{name}=={version} \\", f"    {HASH}", "    # via x"]
    return "\n".join(lines) + "\n"


def write(path: Path, runtime: dict, dev: dict, extra_runtime=(), extra_dev=()):
    path.mkdir(parents=True, exist_ok=True)
    (path / "pyproject.toml").write_text('[project]\nname = "x"\ndependencies = []\n', encoding="utf-8")
    (path / "requirements.txt").write_text(req(runtime, extra_runtime), encoding="utf-8")
    (path / "requirements-dev.txt").write_text(req(dev, extra_dev), encoding="utf-8")
    return path


class Fake:
    """The PyPI version endpoint for (name, version) pairs; anything else 404."""

    def __init__(self, releases=None, fail=None):
        self.releases = releases or {}
        self.fail = fail or set()
        self.calls = []

    def __call__(self, url, headers, timeout):
        self.calls.append(url)
        for (name, version), doc in self.releases.items():
            if url == f"https://pypi.org/pypi/{name}/{version}/json":
                if (name, version) in self.fail:
                    return 503, {}, b""
                return 200, {}, json.dumps(doc).encode()
        return 404, {}, b"{}"


def release(name, version, licence="MIT", wheel="py3-none-any"):
    files = [{"filename": f"{name}-{version}-{wheel}.whl"}] if wheel else []
    files.append({"filename": f"{name}-{version}.tar.gz"})
    return {"info": {"license_expression": licence}, "urls": files}


def run(tmp_path, base, head, fetch, extra=()):
    out = tmp_path / "review.md"
    code = R.main(
        [str(base), str(head), "--config", str(CONFIG), "--out", str(out), *extra],
        fetch=fetch,
        sleep=lambda s: None,
    )
    return code, out.read_text(encoding="utf-8")


# --- scanning --------------------------------------------------------------


def test_scan_real_requirements_has_no_problems():
    for name, count in (("requirements.txt", 98), ("requirements-dev.txt", 122)):
        scan = R.scan_requirements((REPO / "serve_api" / name).read_text(encoding="utf-8"), name)
        assert len(scan.pins) == count
        assert scan.problems == []


def test_scan_unhashed_pin_is_a_problem_not_an_error():
    scan = R.scan_requirements("foo==1.0\nbar==2.0 \\\n    " + HASH + "\n", "requirements.txt")
    assert set(scan.pins) == {"foo", "bar"}
    assert [(p.rule, p.key) for p in scan.problems] == [("hashes", "foo")]


@pytest.mark.parametrize(
    "line",
    [
        "--index-url https://mirror.example/simple",
        "-i https://mirror.example/simple",
        "--extra-index-url=https://mirror.example/simple",
        "--find-links ./wheels",
        "-f ./wheels",
        "-f./wheels",
        "--trusted-host mirror.example",
        "-e ./local",
        "--editable git+https://example/x.git",
    ],
)
@pytest.mark.parametrize("file", ["requirements.txt", "requirements-dev.txt"])
def test_source_option_lines_block_in_either_file(tmp_path, line, file):
    base = write(tmp_path / "base", {"a": "1.0"}, {"a": "1.0"})
    head = write(
        tmp_path / "head",
        {"a": "1.0"},
        {"a": "1.0"},
        extra_runtime=[line] if file == "requirements.txt" else [],
        extra_dev=[line] if file == "requirements-dev.txt" else [],
    )
    code, report = run(tmp_path, base, head, Fake())
    assert code == 1
    assert "**source**" in report and file in report


